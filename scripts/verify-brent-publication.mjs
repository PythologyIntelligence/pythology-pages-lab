import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const page = read('ask-brent.html');
const script = read('brent-ai.js');
const style = read('brent-ai.css');
const build = read('scripts/build-lab.sh');
const nav = read('site.js');
const about = read('about.html');
const home = read('index.html');
for (const word of ['Oracle','Nemesis','Félagskapr','Chathams','Prometheus','invest']) assert.ok(page.includes(word), 'Missing editorial subject: ' + word);
assert.match(page,/data-brent-chat/);
assert.match(page,/id="brent-story"/);
assert.match(page,/brent-ai\.css/);
assert.match(page,/brent-ai\.js/);
assert.doesNotMatch(page, /Kia ora|FinRobot|forex|agricultural-intelligence/i);
assert.match(script,/public-founder-story-20260928/);
assert.match(script,/https:\/\/brentai-api\.pythology\.co\.nz\//);
assert.doesNotMatch(script,/lambda-url\.ap-southeast-1\.on\.aws/);
assert.match(script,/knowledgeReady/);
assert.match(script,/REQUIRED_BRIEFS/);
assert.doesNotMatch(script,/innerHTML|OPENKBS_API_KEY|ANTHROPIC_API_KEY/);
assert.match(nav,/\['ask-brent.html', 'Ask BrentAI'\]/);
assert.match(about,/id="meet-brentai"/);
assert.match(home,/href="ask-brent.html"/);
for (const path of ['ask-brent.html','brent-ai.css','brent-ai.js']) assert.ok(build.includes('  ' + path + '\n'), 'Missing build override: ' + path);
assert.ok(style.length > 1500);
console.log('BrentAI Pages Lab publication contracts passed.');
